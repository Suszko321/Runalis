import assert from 'node:assert/strict';
import {createPlayer,addItem} from '../src/player.js';
import {createCapitalHubWorld} from '../src/hubSystem.js';
import {createAdventurersLounge} from '../src/act1OpeningSystem.js';
import {normalizeProfileSave} from '../src/saveProfiles.js';
import {recordEnemyCombatContribution,grantSharedCombatKillXp} from '../src/combatProgression.js';
import {updateSimulatedSubclassPlayers} from '../src/simulatedSubclassPlayers.js';
import {hireGuildAdventurer,updateLivingAdventurers,getHiredAdventurer,changeAdventurerContract,transferAdventurerGear} from '../src/livingAdventurers.js';

const player=createPlayer('Test');
const game={player,world:createCapitalHubWorld(),log(){}};
const vendor=game.world.objects.find(o=>o.guildContractVendor);
Object.assign(player,{x:vendor.x,y:vendor.y,gold:499});
updateLivingAdventurers(game,1/60);
assert.equal(getHiredAdventurer(game.world),undefined);
assert(!hireGuildAdventurer(game,vendor,player));
assert.equal(player.gold,499);
player.gold=1100;
assert(hireGuildAdventurer(game,vendor,player,()=>.25));
updateLivingAdventurers(game,1/60);
const first=getHiredAdventurer(game.world);
assert(first?.equipment.weapon);
assert(hireGuildAdventurer(game,vendor,player,()=>.55));
updateLivingAdventurers(game,1/60);
assert.equal(player.gold,100);
assert.equal(game.world.objects.filter(o=>o.livingAdventurer).length,1);
assert.notEqual(getHiredAdventurer(game.world).classId,first.classId);

game.world=createAdventurersLounge();
Object.assign(player,game.world.spawn);
updateLivingAdventurers(game,1/60);
const bench=game.world.objects.find(o=>o.livingAdventurer&&!o.hiredAdventurer);
assert.equal(bench.id,first.id);
Object.assign(player,{x:bench.x,y:bench.y});
assert(addItem(player,'apprenticeRobe',1,{upgradeTier:3,gearRarity:'common',rarityRollVersion:1}));
const gear=player.inventory.find(o=>o.id==='apprenticeRobe');
assert(transferAdventurerGear(game,bench,player,'chest',gear.instanceId));
assert.equal(bench.equippedGear.chest.upgradeTier,3);
assert(!player.inventory.includes(gear));
assert(transferAdventurerGear(game,bench,player,'chest'));
assert(player.inventory.includes(gear));
assert(transferAdventurerGear(game,bench,player,'chest',gear.instanceId));
assert(changeAdventurerContract(game,bench,player,true));
updateLivingAdventurers(game,1/60);
assert.equal(getHiredAdventurer(game.world).id,bench.id);
assert.equal(game.world.objects.filter(o=>o.hiredAdventurer).length,1);

const enemy={id:'training-patrol',x:bench.x,y:bench.y,maxHp:100};
recordEnemyCombatContribution(enemy,bench,'blade',100,{source:'weapon'});
grantSharedCombatKillXp(bench,enemy,1000);
assert(bench.skillState.combat.level>1);
assert(bench.skillState.skills.lightArmour.level>1);
assert.equal(bench.skillState.skills.heavyArmour.level,1);
bench.hp=0;
updateLivingAdventurers(game,1);
assert.equal(bench.hp,0);
assert(bench.adventurerDowned);
assert.equal(getHiredAdventurer(game.world),bench);
for(let i=0;i<18;i++)updateLivingAdventurers(game,1);
assert.equal(bench.hp,0);
const saved=normalizeProfileSave(JSON.parse(JSON.stringify(player)));
const restored={player:saved,world:createAdventurersLounge()};
updateLivingAdventurers(restored,1);
const revived=getHiredAdventurer(restored.world);
assert.equal(revived.hp,revived.maxHp);
assert.equal(revived.equippedGear.chest.instanceId,gear.instanceId);
assert.equal(revived.skillState.combat.level,bench.skillState.combat.level);

restored.world.safeZone=false;
restored.world.mode='dungeon';
const target={id:'ordinary-hostile',kind:'hollowling',x:revived.x+45,y:revived.y,hp:45,maxHp:45,r:12,xp:20};
restored.world.enemies.push(target);
for(let i=0;i<1200;i++)updateSimulatedSubclassPlayers(restored,1/60,10+i/60);
assert(target.hp<45,'Active adventurer engages an ordinary hostile');
console.log('PASS vendor fee, one active hire, upstairs bench, exact gear transfer, armour XP, downed recovery, save/reload and live combat.');
