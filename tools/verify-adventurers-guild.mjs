import assert from 'node:assert/strict';
import {createCapitalHubWorld} from '../src/hubSystem.js';
import {createPlayer} from '../src/player.js';
import {createDialogueState,openDialogue,updateDialogue} from '../src/dialogueSystem.js';
import {handleGuildContract} from '../src/adventurersGuildContracts.js';
import {createSaveState,applySaveToGame} from '../src/gameSave.js';
import {nearestObject} from '../src/gameInteraction.js';
import {useGuildStairs} from '../src/act1OpeningSystem.js';
import {updateLivingAdventurers} from '../src/livingAdventurers.js';

const world=createCapitalHubWorld(),player=createPlayer('Guild test');
const game={world,player,canvas:{width:960,height:600},camera:{},log(){},dialogue:createDialogueState()};
const factor=world.objects.find(o=>o.guildContractVendor);
assert(factor && world.buildings.some(b=>b.name==='Adventurers Guild'));
assert(openDialogue(game.dialogue,factor,player,world));
for(let i=0;i<300;i++)updateDialogue(game.dialogue,1/30);
assert.equal(game.dialogue.options.filter(o=>o.action?.startsWith('guild-contract-')).length,6);
assert(game.dialogue.options.some(option=>option.action==='guildHireAdventurer'&&option.text.includes('500 gold')));
const elk='guild-contract-elk';
player.bossKills.theHollowElk=1;
assert(handleGuildContract(player,elk));
assert(!handleGuildContract(player,elk));
player.bossKills.theHollowElk++;
const gold=player.gold;
assert(handleGuildContract(player,elk));
assert(!handleGuildContract(player,elk));
assert.equal(player.gold,gold+120);
const stairs=world.objects.find(o=>o.id==='orrakaiGuildStairs');
Object.assign(player,{x:stairs.x,y:stairs.y+22});
assert.equal(nearestObject(game),stairs);
updateLivingAdventurers(game,1/60);
assert(!world.objects.some(o=>o.livingAdventurer));
assert(useGuildStairs(game,true));
updateLivingAdventurers(game,1/60);
assert.equal(game.world.objects.filter(o=>o.livingAdventurer).length,0);
assert(applySaveToGame(game,JSON.parse(JSON.stringify(createSaveState(game)))));
assert.equal(game.world.mode,'adventurersLounge');
assert.equal(nearestObject(game)?.id,'guildLoungeStairs');
assert(useGuildStairs(game,false));
assert.equal(game.world.mode,'capital');
console.log('PASS guild dialogue, boss proof and one-time reward, lounge arrival, saves and return stairs.');
