import assert from 'node:assert/strict';
import {createPlayer,gainXp} from '../src/player.js';
import {addCombatXP,addPlayerSkillXP} from '../src/skills.js';
import {grantAbilityMasteryXp} from '../src/abilityMasterySystem.js';
import {recordEnemyCombatContribution,grantSharedCombatKillXp} from '../src/combatProgression.js';

const player=createPlayer('Owner'), companion=createPlayer('Companion');
companion.livingAdventurer=true;
const contract={id:'guild-hire-1',hired:true};
player.worldMemory={livingAdventurers:[contract]};
gainXp(player,'foraging',100,undefined,{skipClassXpMultiplier:true});
assert.equal(player.skillState.skills.foraging.xp,90);
assert.equal(addPlayerSkillXP(player,'fishing',100).xpAdded,90);
assert.equal(grantAbilityMasteryXp(player,'graveSpark',10),9);
assert.equal(addCombatXP(player,100).xpAdded,90);
assert(Math.abs(contract.sharedXpPending-27.9)<1e-8);
const before=contract.sharedXpPending;
const enemy={id:'victim',x:0,y:0,xp:100};
recordEnemyCombatContribution(enemy,companion,'blade',10,{source:'weapon'});
recordEnemyCombatContribution(enemy,player,'blade',90,{source:'weapon'});
grantSharedCombatKillXp(player,enemy,100);
assert.equal(companion.skillState.combat.xp,0);
assert.equal(player.lastCombatReward.combatXP,90);
assert(Math.abs(contract.sharedXpPending-before-9)<1e-8);
const kill={id:'final-hit',x:0,y:0,xp:100};
recordEnemyCombatContribution(kill,companion,'blade',100,{source:'weapon'});
grantSharedCombatKillXp(companion,kill,100);
grantSharedCombatKillXp(companion,kill,100);
assert.equal(companion.skillState.combat.xp,100);
contract.hired=false;
assert.equal(addCombatXP(player,100).xpAdded,100);
console.log('PASS skill, mastery and combat penalty, net companion share, final-hit credit and no duplicate award.');
