const cachedPaths=new Map();
export function getAbilityIconPath(ability) {
  return LEGACY_SKILL_ART[ability?.id]?.path || TECHNIQUE_ICON_PATHS[ability?.effectProfile] || null;
}
export function getAbilityIconPalette(ability) {
  return SHARED_SKILL_PALETTES[ability?.id] || CLASS_COMBAT_PALETTES[ability?.classId] || ['#b9b19a','#f5ecd5','#393c3e'];
}
export function techniqueIconMarkup(ability) {
  if(!getAbilityIconPath(ability))return null;
  return `<img class="technique-icon" src="assets/combat-icons/${ability.id}.svg" alt="" aria-hidden="true">`;
}
export function drawTechniqueIcon(ctx,ability,x,y,size) {
  const path=getAbilityIconPath(ability);if(!path || typeof Path2D==='undefined')return false;
  if(!cachedPaths.has(path))cachedPaths.set(path,new Path2D(path));
  const [color,light,dark]=getAbilityIconPalette(ability);
  ctx.save();ctx.translate(x,y);ctx.scale(size/48,size/48);
  ctx.fillStyle=dark;ctx.fillRect(1,1,46,46);ctx.strokeStyle=color;ctx.lineWidth=1;ctx.strokeRect(2,2,44,44);
  ctx.lineJoin='round';ctx.lineCap='round';ctx.strokeStyle='#15191c';ctx.lineWidth=5;ctx.stroke(cachedPaths.get(path));
  ctx.strokeStyle=light;ctx.lineWidth=2.4;ctx.stroke(cachedPaths.get(path));ctx.restore();return true;
}
